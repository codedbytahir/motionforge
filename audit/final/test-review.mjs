import assert from 'node:assert/strict';
import React from '../../packages/motionforge/node_modules/react/index.js';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../../packages/motionforge/package.json',import.meta.url));
const {renderToStaticMarkup}=require('react-dom/server');
const lib=await import('../../packages/motionforge/dist/index.js');
const cachemod=await import('../../packages/motionforge/dist/renderer/index.js');
console.log('renderer exports',Object.keys(cachemod));
assert.throws(()=>lib.range(0,10,0),RangeError);
assert.equal(lib.interpolate(25,[0,10,20],[0,100,150],{extrapolateRight:'extend'}),175);
assert.throws(()=>lib.interpolate(2,[0,0],[0,1]),RangeError);
const Capture=()=>React.createElement('b',null,lib.useCurrentFrame());
const html=renderToStaticMarkup(React.createElement(lib.FrameProvider,{durationInFrames:100,width:100,height:100,initialFrame:25},React.createElement(lib.Sequence,{from:20},React.createElement(Capture))));
assert.match(html,/<b>5<\/b>/);
console.log('manual review regressions PASS');
const {FrameCache}=cachemod;
const cache=new FrameCache({maxSize:8});
cache.set('', 'abcd');cache.set('next','abcd');
assert.equal(cache.get(''),null);
assert.equal(cache.get('next'),'abcd');
cache.set('huge','0123456789');assert.equal(cache.get('huge'),null);
assert.ok(cache.getStats().size<=8);
assert.throws(()=>new FrameCache({maxSize:-1}),RangeError);
console.log('cache regression PASS');
